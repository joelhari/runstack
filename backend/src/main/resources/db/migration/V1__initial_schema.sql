CREATE TABLE activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fit_file_hash VARCHAR(64),
    name VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    date TIMESTAMP WITHOUT TIME ZONE,
    distance REAL,
    duration INTERVAL,
    average_pace INTERVAL,
    PRIMARY KEY (id),
    CONSTRAINT uk_activity_fit_file_hash UNIQUE (fit_file_hash)
);

CREATE TABLE activity_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    activity_id BIGINT NOT NULL,
    recorded_at TIMESTAMP WITHOUT TIME ZONE,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    altitude REAL,
    heart_rate INTEGER,
    speed REAL,
    distance REAL,
    cadence INTEGER,
    power INTEGER,
    temperature INTEGER,
    vertical_oscillation REAL,
    ground_contact_time_ms REAL,
    respiration_rate INTEGER,
    PRIMARY KEY (id),
    CONSTRAINT fk_activity_record_activity
        FOREIGN KEY (activity_id) REFERENCES activity (id) ON DELETE CASCADE
);

CREATE INDEX idx_activity_record_activity_recorded_at
    ON activity_record (activity_id, recorded_at);
