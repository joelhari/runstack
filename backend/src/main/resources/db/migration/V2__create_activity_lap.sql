CREATE TABLE activity_lap (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    activity_id BIGINT NOT NULL,
    lap_index INTEGER NOT NULL,
    started_at TIMESTAMP WITHOUT TIME ZONE,
    ended_at TIMESTAMP WITHOUT TIME ZONE,
    elapsed_duration INTERVAL,
    timer_duration INTERVAL,
    distance REAL,
    average_pace INTERVAL,
    average_speed REAL,
    maximum_speed REAL,
    average_heart_rate INTEGER,
    maximum_heart_rate INTEGER,
    average_cadence INTEGER,
    maximum_cadence INTEGER,
    average_power INTEGER,
    maximum_power INTEGER,
    calories INTEGER,
    ascent INTEGER,
    descent INTEGER,
    PRIMARY KEY (id),
    CONSTRAINT fk_activity_lap_activity
        FOREIGN KEY (activity_id) REFERENCES activity (id) ON DELETE CASCADE,
    CONSTRAINT uk_activity_lap_index UNIQUE (activity_id, lap_index)
);

CREATE INDEX idx_activity_lap_activity_started_at
    ON activity_lap (activity_id, started_at);
